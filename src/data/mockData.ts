// Helper to read permanently saved profile from storage
const getStoredCustomProfile = (keyFilter?: string): { name?: string; avatar?: string; accountId?: string } => {
  if (typeof window === 'undefined') return {};
  try {
    const saved = localStorage.getItem('yalla_permanent_user_profile_v5');
    if (saved) {
      const p = JSON.parse(saved);
      if (!keyFilter || p.id === keyFilter || p.accountId === keyFilter || p.email === keyFilter) {
        return {
          name: p.name || undefined,
          avatar: p.avatar || undefined,
          accountId: p.accountId || undefined,
        };
      }
    }
  } catch {}
  return {};
};

